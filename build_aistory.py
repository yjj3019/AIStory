def build_html():
    scenes_js = []
    for idx, (year, title, who, lines) in enumerate(CHAPTERS, start=1):
        ls = "\n".join("      " + js_str(l) + "," for l in lines)
        extra = ""
        vis = CHAPTER_VISUALS.get(idx)
        if vis:
            if "stats" in vis:
                extra += ",\n    stats:" + json.dumps(vis["stats"], ensure_ascii=False)
            if "table" in vis:
                extra += ",\n    table:" + json.dumps(vis["table"], ensure_ascii=False)
            if "hook" in vis:
                extra += ",\n    hook:" + json.dumps(vis["hook"], ensure_ascii=False)
            if "terms" in vis:
                extra += ",\n    terms:" + json.dumps(vis["terms"], ensure_ascii=False)
            for field in ("learning_question", "learning_answer"):
                if field in vis:
                    extra += ",\n    " + field + ":" + json.dumps(vis[field], ensure_ascii=False)
            if "src" in vis:
                extra += ",\n    src:" + json.dumps(vis["src"], ensure_ascii=False)
        scenes_js.append(
            "  {\n"
            f"    year:{js_str(year)},\n"
            f"    title:{js_str(title)},\n"
            f"    part:{PART_OF[idx - 1]},\n"
            f"    who:[{','.join(js_str(w) for w in who)}],\n"
            f"    lines:[\n{ls}\n  ]{extra}\n"
            "  }"
        )
    scenes_block = "const SCENES = [\n" + ",\n".join(scenes_js) + "\n];"
    p_block = "const P = " + json.dumps(P, ensure_ascii=False, indent=1) + ";"
    r_block = "const RIVALS = " + json.dumps(RIVALS, ensure_ascii=False, indent=1) + ";"
    roll = ROLL_HTML
    from extract_narration import narration_from_source, audio_status, json_text
    narration = narration_from_source(globals())
    status = audio_status(narration, ROOT)
    data = "const NARRATION = " + json_text(narration).strip() + ";\n" + "const AUDIO_STATUS = " + json_text(status).strip() + ";\n" + "\n\n".join([p_block, r_block, "const EXTRAS = {\n};", scenes_block]) \
        + "\n\nObject.assign(RIVALS, EXTRAS);" \
        + "\nconst PARTS = " + json.dumps(PART_INFO, ensure_ascii=False) + ";" \
        + "\nconst PART_TEXT = " + json.dumps(PART_TEXT, ensure_ascii=False) + ";" \
        + "\nconst END_QUOTE = " + json.dumps(ENDING_TEXT, ensure_ascii=False) + ";" \
        + "\nconst ROLL_HTML = " + json.dumps(roll, ensure_ascii=False) + ";"
    tpl = (ROOT / "slide.template.html").read_text(encoding="utf-8")
    assert "/*DATA*/" in tpl and "const AUDIO_DIR='audio/'" in tpl
    html = tpl.replace("/*DATA*/", data).replace("const AUDIO_DIR='audio/'", "const AUDIO_DIR='audio18/'")
    html = html.replace("<title>인공지능을 만든 사람들 — 슬라이드</title>", "<title>인공지능을 만든 사람들 — AIStory</title>")
    return html


